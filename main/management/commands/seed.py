class Command(BaseCommand):
    help = "Заполняет каталог демонстрационными фильмами"

    def handle(self, *args, **options):
        created = 0
        for title, original, year, director, duration, description, genres in FILMS:
            movie, was_created = Movie.objects.get_or_create(
                title=title, year=year,
                defaults={
                    "original_title": original, "director": director,
                    "duration": duration, "description": description,
                },
            )
            if was_created:
                created += 1
                for name in genres:
                    genre, _ = Genre.objects.get_or_create(name=name)
                    movie.genres.add(genre)
        self.stdout.write(self.style.SUCCESS(f"Добавлено фильмов: {created}"))
